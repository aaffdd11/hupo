// 「**他明说才许写**」那条闸（P1-22 · 契约 `docs/dev/59-USER-APPS.md` §八 第 1 条 · D4.18）。
//
// ── 为什么要有它 ────────────────────────────────────────────
// 造一个小程序 = **在他自己的桌面上放一个东西**。这件事只有**他张嘴要**才许做：
// 助手自己想到的、或者从别处（网页、别人发来的内容）读到的主意，**只能提一句**（D4.18）。
//
// 原来这条规矩只有**两道软的**：工具说明里写着、事后审计留痕。而**说明是给模型看的**——
// 模型被绕进去了就照着做，那两道一道也拦不住。
// ⇒ 服务端在**写盘之前**自己看一遍：**这一轮他到底说了什么**。
//
// ── 看的是"他那句话"，不是"请求里带了什么" ──────────────────
// 🔴 判据只读**服务端自己记下来的当轮输入**（`dispatcher.turnInput`）。
//    请求里就算写着"他明说了"也**一眼都不看** —— 与"身份只从 `ctx.sub` 来"同一条纪律。
//    看请求里的字段，等于把闸交给**要过闸的那个人**。
//
// ── 判据的方向：宁可误拒 ────────────────────────────────────
// ⚠️ **这是产品规则，而"什么算明说"主人还没拍**（`docs/dev/77-BLOCKERS.md` B8）。
//    那儿取的是**保守默认**：认不出"他张嘴要了"就**拒**，并在话里告他**该怎么说**。
//    代价是**多问一句**（他再说一句就补回来了）；反过来放过去，
//    代价是**他桌面上多了一个他没要的东西**——那正是这条决策要防的那一侧。

/**
 * 他"张嘴要"的说法。**必须与下面的动词同时出现**（见 [#asksToMakeApp]）。
 *
 * ⚠️ 只留"**对人提要求**"的那几个说法。`请` 单独一个**不算** ——
 *    "请问这是什么"里也有 `请`，那不是在要东西。
 */
const ASK = /(帮我|给我|替我|请你|麻烦|能不能|可不可以|可以帮我|我要|我想|我想要|来个|来一个|做一个|做个)/;

/**
 * 做的动作。**光有它不算**（"我今天做了一个梦"）—— 要和 [#ASK] 凑一块儿。
 *
 * ⚠️ `打开`／`看看`／`删` **不在里面**，也不该在里面：那些**不是造**。
 *    闸只管"造一个他没要的东西"；打开、看、卸掉各有各的规矩。
 */
const MAKE = /(做|造|写|加|弄|搞|生成|创建|新建|来)/;

/** 拒了的时候跟他说的话。**人话**（会经模型转述给他），而且要说清"该怎么办"。 */
export const NEEDS_ASK =
  '这个我没动手：往你桌面上放东西，得你亲口说一句"帮我做一个……"我才做。'
  + '你要是想让我做，说一声就行；刚才要是从别处看来的主意，我就不动手了。';

/**
 * 这一轮他到底有没有"明说要做"。
 *
 * @param {unknown} turnInput 当轮他自己说的那句话（服务端记的，**不是请求里来的**）
 * @returns {boolean} 认得出"他要我做" ⇒ `true`
 *
 * ⚠️ 空 / 不是字符串 ⇒ `false`（**fail-closed**）：没有输入就没有"明说"这回事。
 *    这条同时管住一件事：**助手自己发起的那一轮**（定时、重做、别人代投）
 *    没有"他那句话" ⇒ 一律不许写盘 —— 与 D4.18"自己想到的只许提"对得上。
 */
export function asksToMakeApp(turnInput) {
  if (typeof turnInput !== 'string') return false;
  const t = turnInput.trim();
  if (!t) return false;
  return ASK.test(t) && MAKE.test(t);
}
