// 「**他明说才许写**」那条闸（P1-22 · 契约 `docs/dev/59-USER-APPS.md` §八 第 1 条 · D4.18）。
//
// ── 为什么要有它 ────────────────────────────────────────────
// 造一个小程序 = **在他自己的桌面上放一个东西**。这件事只有**他张嘴要**才许做：
// 助手自己想到的、或者从别处（网页、别人发来的内容）读到的主意，**只能提一句**（D4.18）。
//
// 原来这条规矩只有**两道软的**：工具说明里写着、事后审计留痕。而**说明是给模型看的**——
// 模型被绕进去了就照着做，那两道一道也拦不住。
// ⇒ 服务端在**写盘之前**自己看一遍：**这一轮他到底说了什么**。
//
// ── 看的是"他那句话"，不是"请求里带了什么" ──────────────────
// 🔴 判据只读**服务端自己记下来的当轮输入**（`dispatcher.turnInput`）。
//    请求里就算写着"他明说了"也**一眼都不看** —— 与"身份只从 `ctx.sub` 来"同一条纪律。
//    看请求里的字段，等于把闸交给**要过闸的那个人**。
//
// ── 判据的方向：宁可误拒 ────────────────────────────────────
// ⚠️ **这是产品规则，而"什么算明说"主人还没拍**（`docs/dev/77-BLOCKERS.md` B8）。
//    那儿取的是**保守默认**：认不出"他张嘴要了"就**拒**，并在话里告他**该怎么说**。
//    代价是**多问一句**（他再说一句就补回来了）；反过来放过去，
//    代价是**他桌面上多了一个他没要的东西**——那正是这条决策要防的那一侧。

/**
 * 他"张嘴要"的说法。**必须与下面的动词同时出现**（见 [#asksToMakeApp]）。
 *
 * ⚠️ 只留"**对人提要求**"的那几个说法。`请` 单独一个**不算** ——
 *    "请问这是什么"里也有 `请`，那不是在要东西。
 */
const ASK = /(帮我|给我|替我|请你|请(?!问)|麻烦|能不能|可不可以|可以帮我|我要|我想|我想要|想要|需要一个|需要个|要一个|要个|来个|来一个|做一个|做个)/;

/**
 * 做的动作。**光有它不算**（"我今天做了一个梦"）—— 要和 [#ASK] 凑一块儿。
 *
 * ⚠️ `打开`／`看看`／`删` **不在里面**，也不该在里面：那些**不是造**。
 *    闸只管"造一个他没要的东西"；打开、看、卸掉各有各的规矩。
 */
const MAKE = /(做|造|写|加|弄|搞|生成|创建|新建|搭|实现|来|放到|放进|做成|改成|补上|添)/;

/**
 * ★ **那件东西本身**（2026-10-04 加：主人要的是"**语义上说过就算**"）。
 *
 * ⚠️ 为什么要它：他常常**不带动词**地说一句想要什么 ——
 *    「我要一个能记账的东西」「想要个能玩的小页面」。只认动词的话，
 *    这两种说法都会被拒，而他看到的就是"它又要我补一句'帮我做一个小程序'"。
 * ⇒ 认法放宽成两条（**任一条成立就算"他要我做"**）：
 *    ① 他张嘴要（[ASK]）＋ 他要么说了做的动作（[MAKE]）、**要么点了那件东西**（[OBJECT]）；
 *    ② 他直接说了做的动作 ＋ 那件东西（「做个五子棋」这种主语省略的说法）。
 */
const OBJECT = /(小程序|小应用|小页面|小工具|小游戏|应用|app\b|软件|程序|页面|网页|界面|工具|游戏|东西)/i;

/** 拒了的时候跟他说的话。**人话**（会经模型转述给他），而且要说清"该怎么办"。 */
export const NEEDS_ASK =
  '这个我没动手：往你桌面上放东西，得你亲口说一句要什么 —— 直接说你想要什么就行'
  + '（比如"做一个记账的""我要一个能玩的小页面"），不用套哪一句格式。';

/**
 * ★ **已经在某个小程序里了 ⇒ 不许再开一个小程序**（主人 2026-09-27）：
 * *"只有 main 里面是可以指导它创建小程序的；如果是在 workspace 下面的
 * 小程序里面聊天的话，他无法继续创建小程序"*。
 *
 * 🔴 **判据是"现在这一间是不是已有的一个小程序"**（`apps.has(scope)` 或内置那三格），
 *    **不是** `scope !== main` —— 派活那间（长活"另开一处做"）本来就要在那里
 *    把新 app 造出来，那是这条产品行为的一部分（`job.js` 的注释写着它自己会调
 *    `app_create`）。⇒ 那条路照旧放行。
 *
 * ⚠️ 与 [NEEDS_ASK] 一样：**这是给模型转述的话**，所以是人话、并且说清"该怎么办"。
 */
export const INSIDE_APP_NO_CREATE =
  '这个我没做：小程序里面不能再开一个小程序。回桌面上说一句"帮我做一个……"，我在桌面上给你造。';
  + '你要是想让我做，说一声就行；刚才要是从别处看来的主意，我就不动手了。';

/**
 * 这一轮他到底有没有"明说要做"。
 *
 * @param {unknown} turnInput 当轮他自己说的那句话（服务端记的，**不是请求里来的**）
 * @returns {boolean} 认得出"他要我做" ⇒ `true`
 *
 * ⚠️ 空 / 不是字符串 ⇒ `false`（**fail-closed**）：没有输入就没有"明说"这回事。
 *    这条同时管住一件事：**助手自己发起的那一轮**（定时、重做、别人代投）
 *    没有"他那句话" ⇒ 一律不许写盘 —— 与 D4.18"自己想到的只许提"对得上。
 */
export function asksToMakeApp(turnInput) {
  if (typeof turnInput !== 'string') return false;
  const t = turnInput.trim();
  if (!t) return false;
  // ① 他张嘴要 ＋（说了做的动作 **或** 点了那件东西）：`我要一个能记账的东西`
  if (ASK.test(t) && (MAKE.test(t) || OBJECT.test(t))) return true;
  // ② 说了做的动作 ＋ 那件东西（主语省略的说法）：`把数独内容放到小程序里面` / `做个五子棋`
  return MAKE.test(t) && OBJECT.test(t);
}

/**
 * ★ **他"最近"说过要做一个东西吗**（2026-10-04）。
 *
 * ── 为什么需要它（真机读数）────────────────────────────────
 *   主人做一个小程序，往往**分好几轮**说：先说「请创建一个可以玩飞行棋的游戏」，
 *   接下来几轮全是「骰子要放在各自停机坪旁边」「要有存储啊」这种**改动要求** ——
 *   那些句子里**没有**"造"的意思（它们本来就是"接着说"）。
 *   `apps-socket` 那条闸只看**当轮**那一个问题，于是后面每一轮都被拒 ⇒
 *   他看到的还是"它又要我补一句"。⇒ 往后看**同一条会话里最近那几句话**。
 *
 * ⚠️ **窗口很小**（默认最近 3 句）、**只认同一个 scope**（`apps-socket` 那侧按房间取），
 *    而且**仍然只读服务端自己记的他的话** —— 请求里带什么一个字都不看。
 *
 * @param {unknown} recentInputs 他最近说过的几句（新的在前或后都行，这里全会看一遍）
 */
export function askedRecently(recentInputs, window = 3) {
  if (!Array.isArray(recentInputs)) return false;
  const list = recentInputs.filter((t) => typeof t === 'string' && t.trim() !== '');
  for (const t of list.slice(0, window)) {
    if (asksToMakeApp(t)) return true;
  }
  return false;
}
