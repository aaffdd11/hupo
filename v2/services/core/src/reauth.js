// **"这一步要你重新登一次"** —— 注销那条路上的身份再确认（账 #39 的前一半）。
//
// ── 它防什么 ──────────────────────────────────────────────
// 注销**不可逆**（那一台连同里面的东西一起收掉）。而这条路原来**只认令牌** ⇒
// **一个被盗的令牌就能删掉一个人所有的东西**。
//
// ── 凭什么算"再确认过" ────────────────────────────────────
// 用**令牌里的 `iat`**（= 那一次**真正登录**签发的时刻）：
//
//     `now - iat <= 窗口`  ⇒ 算"刚登录过"，放行；否则 ⇒ 请他重新登一次。
//
// 🔴 **为什么 `iat` 能当这个用**（2026-09-22 看代码确认的）：
//    `Auth.renew()`（续期）**保留原来的 `iat`、只把 `exp` 往前挪**（同一个 `jti`）。
//    ⇒ 拿着一个旧令牌**没法靠续期把 `iat` 刷成新的** —— 只有**真的重新登录**才会新签一个。
//    （这一点要是反的，这条规则就是**空的**：攻击者续一次期就绕过去了。）
//
// ── 两条如实说 ────────────────────────────────────────────
//   ① 在**短信通道接上之前**，这道门和"登录"本身**一样强**（都走那个验证码）——
//      它挡的是"**被盗的旧令牌**"，不是"知道你验证码的人"。
//   ② 读数**Fail-closed**：读不出 `iat` / 窗口不是正数 ⇒ **一律不放行**。
//      （宁可让用户多登一次，也不许"因为读不懂所以放行"。）

/** 多久之内登录过算"刚登录过"。十分钟：够他点完确认，又不至于让一个旧会话一直有效。 */
export const DEFAULT_REAUTH_WINDOW_MS = 10 * 60 * 1000;

/**
 * @param {object} o
 * @param {number} o.iat              令牌里的签发时刻（毫秒）
 * @param {number} [o.now]
 * @param {number} [o.windowMs]
 * @returns {boolean} `true` = 刚登录过，可以继续
 */
export function reauthOk({ iat, now = Date.now(), windowMs = DEFAULT_REAUTH_WINDOW_MS } = {}) {
  if (!Number.isFinite(iat)) return false; // 读不出 ⇒ 不放行
  if (!Number.isFinite(windowMs) || windowMs <= 0) return false; // 窗口配坏 ⇒ 不放行
  // ⚠️ **`iat` 在未来**（机器时钟回拨/偏差）**按"刚刚签发"算** —— 它不是攻击者能控的
  //    （payload 是服务端签的名），所以往"放行"那一侧倒不会削弱什么；
  //    反过来把它当"超期"会让用户**卡在"重新登录"里出不来**（登完还是被拒）。
  return now - iat <= windowMs;
}
