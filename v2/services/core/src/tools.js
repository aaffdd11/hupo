// 哪些工具**不会改东西**。手册决策 **D10.1 / D10.2**（`05-DECISIONS.md` §二·补）。
//
// ── 它解决什么问题 ──────────────────────────────────────────
//
// 「续做」= 把主人的原话**重新派一遍**。所以它会把**已经做过的副作用再做一遍**
// （写文件、发命令、下单）。要安全，就必须能回答一句话：
//
//     **"这件事做过没有？"**
//
// 而这个仓库里**没有任何东西能回答它**（工具结果不进时间线，`07-TIMEOUT.md` §六）。
// ⇒ D10.1 的取法：**只自动续做"整轮只碰过只读工具"的活**，其余只通知。
//
// ── 白名单是**保守**的（D10.2）────────────────────────────
//
// ⚠️ **默认拒绝，不是默认允许。** 不在名单里的一律算"会改东西"。
// ⚠️ **`bash` 不在名单里** —— 一个 shell 能干任何事。
//    代价要先认：**走了 `bash`（哪怕只是 `ls`）就只通知、不自动重来**。
//    宁可少续做，也不能重复下单、重复发信。
//
// ⚠️ 这份名单是**量出来的**，不是想的：SDK profile 现在给 25 个工具
//    （`docs/dev/10-RECONCILE.md` §7.1 记了完整清单）。
//    **DSH 升级加了新工具时，它会自动落到"会改东西"那一类**——这是安全的默认。

/**
 * 不会改东西的工具（按名字）。
 *
 * ⚠️ **冻结的数组，不是 Set**：`Object.freeze` 冻不住 `Set` 的 `add`
 *    （那动的是内部槽，不是属性）⇒ 冻一个 Set 会给人"改不了"的错觉。
 */
export const READ_ONLY_TOOLS = Object.freeze([
  // 读文件和找文件
  'read',
  'read_image',
  'glob',
  'grep',
  // 上网查（D10.1 能立起来，靠的就是这两个是**独立工具**）
  'web_search',
  'web_fetch',
  // 读自己的状态与别的 agent 的状态
  'get_goal',
  'job_list',
  'job_output',
  'list_agents',
  // 加载一段说明（只读）
  'skill',
]);

const READ_ONLY = new Set(READ_ONLY_TOOLS);

/**
 * 这个工具会不会改东西？
 *
 * ⚠️ 名字认不出来 ⇒ **算它会改**（默认拒绝）。空名字、非字符串也一样。
 */
export function isReadOnlyTool(name) {
  return typeof name === 'string' && READ_ONLY.has(name);
}
