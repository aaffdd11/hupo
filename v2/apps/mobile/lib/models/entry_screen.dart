// **没登录的时候，第一屏是哪一屏**（纯逻辑：一处出处，网页与安卓共用一句话）。
//
// ── 主人 2026-09-28 在安卓真机上看到并当场定的 ────────────────
//   原话：*"另外，安卓的首页不是网站的首页，而是那个登录页。所以在安卓上，
//   登录页没有退回首页的箭头。"* ⇒ 问过之后他选：**安卓不要落地页：直接登录页，
//   箭头也去掉**。
//
// ── 为什么两版不一样（这不是"少一个页面"，是两件事）────────────
//   · **落地页**（`landing_screen.dart`）是给**还没用的人**看的：一句"这是什么" ＋
//     两个入口（开始用 / 下载安卓版）。**它长在网页上**；
//   · **已经装了这个包的人**不需要它 —— 他要的是"进来说话"；
//   · 而且那一页上那颗「下载安卓版」，在**安卓包里点它**只会得到一句
//     "你正在用的就是这个安卓版"（诚实，但没意义）。
//   ⇒ 安卓那一版**直接从登录页开始**，登录页顶上那颗"回首页"的箭头也去掉
//     （没有首页可回 —— 留着它点了什么都不该发生，那就是个假按钮）。
//
// 🔴 **网页那一版一个字都不许动**：先落地页 ⇒ 点"开始用" ⇒ 登录页（带箭头回首页）。
//    判据：`test/unit/entry_screen_test.dart`（这条规则本身）＋
//    `test/widget/login_test.dart`（给了 `onBack` 才画箭头）＋
//    `test/widget/landing_transition_test.dart`（网页那条过渡仍然在）。
//
// ⚠️ 楼层：住 `models/`（纯逻辑、无依赖）⇒ 判据能在 VM 上直接量，
//    而"选哪一屏"不必为了可测性去动 `kIsWeb`。

