String waitingElapsedWords(int seconds) {
  final s = seconds < 0 ? 0 : seconds;
  if (s < 60) return '已经等了 $s 秒';
  final m = s ~/ 60;
  return '已经等了 $m 分 ${s % 60} 秒';
}

