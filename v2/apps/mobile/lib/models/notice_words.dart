/// 两处撤销（浮窗里 + 时间线那一条）按钮上的字。
///
/// ⚠️ 它**不由服务端给**：`undo.label` 是服务端那份文案（契约 §五），
///    而当服务端没给 label 时我们**宁可不要这个按钮**也不自己编一句
///    （见 `NoticeUndo.fromJson`）。这一条是界面**自己**的按钮字，
///    所以要进禁用词表被扫。
const noticeUndoLabel = '撤销';

/// 浮窗右上角那个"知道了/关掉"的按钮。
///
/// ⚠️ 非有不可：浮窗**会自己消失**，但它也可能**留在屏幕上**
///    （瞬时那条尤其），那时用户得有一个"我看完了"的入口。
/// ⚠️ **不许写"3 秒后消失"这类话**（契约 §一 第 4 条：不承诺时间）——
///    "知道了"只说"我收到了"，一个字都不承诺。
const noticeDismissLabel = '知道了';

/// 瞬态通知（`notice/urgent`）里那句**我们自己补的话**。
///
/// ⚠️ 为什么这一句是客户端写的：契约 §三① 说得很死——
///    写盘失败时那一条**物理上写不进列表**，所以它**必须自己说清**"这条留不下"。
///    服务端给的是"出了什么事"（`text`，比如「盘满了，这条我没能记下来」），
///    而"**它在屏幕上留不住**"是**屏幕这一侧才知道的事**（列表里到底有没有那一条）。
/// ⇒ 两句一起显示：服务端那句原话 + 这一句补充。
///
/// ⚠️⚠️ **含"记录 / 时间线"的话一个都不许有**：那两个都是禁用词
///    （`forbidden_words.dart`：「时间线」是内部词）。契约 §三① 补的那一行
///    是**服务端那句话**的口径（「盘满了，这条我没能记下来」），
///    不是给这一句用的 —— 这一句得自己干净。
///    `test/unit/notice_test.dart` 有一条断言拿**真那份禁用词表**扫它。
/// ⚠️ **不含任何数字 / 时间承诺**（D7.1：阈值不住在客户端；§一 第 4 条：不承诺时间）。
const noticeNotKeptLine = '这条留不下来，刷新就看不到了';
