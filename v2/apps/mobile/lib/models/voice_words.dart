/// **开麦那一步失败的理由**（机器原因翻成人话；认不出的就说"没打开"）。
///
/// ⚠️ 纯函数：判据直接喂机器原因、量它翻出来的是哪一句。
String voiceMicReason(String why) {
  switch (why) {
    case 'denied':
      return '麦克风没给权限，先允许一下。';
    case 'not-configured':
      return '这台还没配听懂你说话的那把钥匙。';
    case 'unsupported':
      return '这台开不了麦。';
    default:
      return '麦没打开，等下再试。';
  }
}
