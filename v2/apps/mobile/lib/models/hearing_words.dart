// 语音那一步（**真开麦**）在界面上的字。契约：`docs/dev/71-MIC-ASR.md`。
//
// ⚠️ **界面上的字只有这一处**（D3.10）。别在 widget 里写字符串。
// ⚠️ 不许出现内部词（`AGENTS.md` §六 第 4 条）：这里说的都是用户看得见的事
//    —— "麦克风权限"、"没配好"，不是"连接 / 客户端 / 云端 / 工具名"。
//
// 🔴 这一版把主人 2026-09-22 那个**假形状**（`按住 说话` + `演示` 小标）**砍了**：
//    主人 2026-09-23 定案 —— *"我们那个页面，并没有按钮。你做一下按钮。
//    是按一下开始语音跟踪，实时转化语音成文字。再按一下结束。
//    然后将文字展示出来。用户可以选择发送。"*
//    ⇒ 按一下开始 / 再按一下结束，**没有再"按住"那一套**（声明砍掉，见契约 §五）。

/// 按一下开始（闲的时候）。
const String hearStart = '按一下 说话';

/// 正在听（再按一下就是结束）。**"正在听"这三个字只在真的在听时出现**（D5.13）。
const String hearListening = '正在听…再按一下 结束';

/// 在听、但还一个字都没认出来时，那一块里显示的（**和按钮上那句不一样**：
/// 同一屏上同一句话画两遍，看着就像坏了）。
/// ⚠️ 它是真的：这会儿麦克风确实开着（D5.13 管的是"没在听时不许说听"）。
const String hearListeningEmpty = '我在听 —— 你说话就行';

/// **按了结束、等最后一句**的那一小会儿（通常不到一秒，但**必须说出来**：
/// 屏幕上那几个字还没定下来，这时候什么都不显示，用户会以为说丢掉了）。
const String hearFinishing = '收尾中…（把最后一句接住）';

/// 这一批的形状（说清楚按下去会发生什么，别让用户猜）。
const String hearHint = '说完再按一下，字会留在这儿 —— 你自己决定发不发。';

/// 这台部署还没配钥匙（**如实说**，不装开麦）。
const String hearUnavailable = '语音这条路还没配好（缺钥匙）';

/// 浏览器没给麦克风权限。
const String hearDenied = '没拿到麦克风权限 —— 在地址栏那个锁里放开麦克风，再按一次';

/// 开麦这一步本身失败了（没有麦克风、被系统拒、音频图起不来…）。
const String hearFailed = '开不了麦克风，再按一次试试';

/// **这条连接没接上**（不是麦克风的事：中间那一跳不认这条路径、网断了…）。
/// ⚠️ 它必须和 [hearFailed] **分开说** —— 混成一句就是页面在说假话。
const String hearNoEntry = '这条路暂时连不上，等会儿再按一次';

/// 识别那一头出错了。
const String hearEngineFailed = '识别那一头出错了，再按一次试试';

/// 到点了（内测版一条连接最多一分钟）——服务端说的，不是我们猜的。
const String hearCapped = '一次最多说一分钟，我先停了';

/// 一个字都没听着。
const String hearNothing = '什么都没听到，再按一次试试';
