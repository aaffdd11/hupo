/// 排着 **n** 条时那句抬头（DSH `queue.count` 的 `{n} 条排队消息`）。
///
/// 🔴 那个 `n` **必须**是"现在真画得出来的行数"（`ChatQueue.count` 数出来的），
///    不许抄服务端另给的那个数 —— 两边一对不上，屏幕上就会出现
///    "3 条排队消息"底下只有两行（N10：宁可不显示，也不说假话）。
String queueCountHeader(int n) => '$n 条排队消息';

/// 那一条上"撤掉它"的按钮（既是悬停提示，也是无障碍名）。
///
/// ⚠️ **说的是结果，不是动作**："不发了" = 这件事我不等了 —— 比"删除"更像人话，
///    而且它**如实**：撤掉的正是"还没轮到它跑"的那一句。
/// ⚠️ **已经在跑的那句撤不掉**（服务端结构上不给这一步，见契约 §二）——
///    所以这一句**不许**写成"撤回它已经做过的事"。
const String queueCancelLabel = '不发了';

/// 两条以上时那个抬头（点它展开/收起）的无障碍名。
///
/// ⚠️ 抬头本身带着那句计数（`queueCountHeader`）——它是**看得见的**字；
///    这一句只是**给读屏的那半边**说清"点它会发生什么"。
